"""Writes the icon picker's emoji table from Unicode's emoji-test.txt.

Usage: gen_emoji_data.py path/to/emoji-test.txt > \
    src/chrome/browser/ui/views/tabs/vertical/alerse_emoji_data.inc

The Chromium tree carries emoji-test.txt, e.g.
third_party/rust/chromium_crates_io/vendor/unicode-width-v0_2/tests/.
Kept: fully qualified emoji up to Emoji 15.0 (what Segoe UI Emoji and Apple
Color Emoji both draw), without skin tones (as Arc's and the macOS palette's
grid), in the macOS palette's eight categories and order.
"""

import re
import sys

MAX_VERSION = 15.0
GROUPS = {
    'Smileys & Emotion': 0,
    'People & Body': 0,
    'Animals & Nature': 1,
    'Food & Drink': 2,
    'Activities': 3,
    'Travel & Places': 4,
    'Objects': 5,
    'Symbols': 6,
    'Flags': 7,
}


def c_string(text):
    out = []
    for byte in text.encode('utf-8'):
        if byte < 0x20 or byte >= 0x7F or byte in (0x22, 0x5C):
            out.append('\\x%02x' % byte)
        else:
            out.append(chr(byte))
    # Split after hex escapes so a following hex digit is not swallowed.
    return '"' + '""'.join(re.split(r'(?<=\\x[0-9a-f]{2})(?=[0-9A-Fa-f])',
                                    ''.join(out))) + '"'


def main(path):
    categories = [[] for _ in range(8)]
    group = None
    for line in open(path, encoding='utf-8'):
        match = re.match(r'# group: (.*)', line)
        if match:
            group = GROUPS.get(match.group(1).strip())
            continue
        if group is None or line.startswith('#') or not line.strip():
            continue
        match = re.match(
            r'([0-9A-F ]+);\s*fully-qualified\s*#\s*\S+\s+E(\d+\.\d+)\s+(.*)',
            line)
        if not match or float(match.group(2)) > MAX_VERSION:
            continue
        points = [int(p, 16) for p in match.group(1).split()]
        if any(0x1F3FB <= p <= 0x1F3FF for p in points):
            continue
        categories[group].append((''.join(map(chr, points)),
                                  match.group(3).strip().lower()))
    print('// Generated by tools/gen_emoji_data.py from Unicode\'s '
          'emoji-test.txt. Do not edit.')
    print('// clang-format off')
    print('constexpr PickerEmojiEntry kPickerEmojiTable[] = {')
    starts = []
    count = 0
    for category, entries in enumerate(categories):
        starts.append(count)
        for text, name in entries:
            print('    {%s, %s},' % (c_string(text), c_string(name)))
            count += 1
    print('};')
    print('constexpr size_t kPickerEmojiCategoryStarts[] = {%s};' %
          ', '.join(map(str, starts)))
    print('// clang-format on')


if __name__ == '__main__':
    main(sys.argv[1])
